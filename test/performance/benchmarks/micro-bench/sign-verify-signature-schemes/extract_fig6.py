#!/usr/bin/env python3
"""Extract `go test -bench` output into fig6.dat for fig6.gpi.

Inputs:
  * ncircle aggsig/multisig benchmark output (aggsig/bgls03, multisig/b03,
    multisig/bgoy07). Produced by:
        cd ncircle
        go test -v -bench=. -benchmem ./aggsig/bgls03 ./multisig/b03 ./multisig/bgoy07
  * cryptofun benchmark output restricted to RSA and Ed25519 sign/verify:
        cd cryptofun
        go test -v -bench='RSASignSHA256|RSAVerifySHA256|Ed25519phSign|Ed2519phVerify' -benchmem

Output format (matches fig6-sample.data):
  numSigs  RSA.sign  RSA.verify  ED25519.sign  ED25519.verify \
           BGLS03.sign BGLS03.verify B03.sign B03.verify BGOY07.sign BGOY07.verify

Interpretation rules (from fig6-sample.data's header):
  * RSA/Ed25519 "sign" column is the time for a single sign (independent of
    numSigs) because they are non-aggregatable.
  * RSA/Ed25519 "verify" column is numSigs * single-verify time. At numSigs=0
    we duplicate the numSigs=1 value so the plot looks nice.
  * Aggregate/multisig "sign" column at numSigs=N is the cost of the next
    Sign call when N prior signatures are already in the aggregate
    (BenchmarkSign/numPrevSigs:N).
  * Aggregate/multisig "verify" column at numSigs=N is BenchmarkVerify/numSigs:N.
    At numSigs=0 we duplicate numSigs=1.
"""

import argparse
import re
import sys

PKG_RE = re.compile(r"^pkg:\s*(\S+)")
BENCH_RE = re.compile(r"^(Benchmark\S+?)-\d+\s+\d+\s+([\d.eE+\-]+)\s+ns/op")

RSA_KEYLEN = 3072
NS = [0, 1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024]

CRYPTOFUN_PKG = "github.com/etclab/cryptofun"
BGLS03_PKG = "github.com/etclab/ncircl/aggsig/bgls03"
B03_PKG = "github.com/etclab/ncircl/multisig/b03"
BGOY07_PKG = "github.com/etclab/ncircl/multisig/bgoy07"


def parse(paths):
    results = {}
    current_pkg = None
    for path in paths:
        with open(path) as f:
            for line in f:
                m = PKG_RE.match(line)
                if m:
                    current_pkg = m.group(1)
                    continue
                m = BENCH_RE.match(line)
                if m and current_pkg is not None:
                    results[(current_pkg, m.group(1))] = int(round(float(m.group(2))))
    return results


def get(results, pkg, name, *, required=True):
    key = (pkg, name)
    if key in results:
        return results[key]
    if required:
        print(f"warning: missing {name} in {pkg}", file=sys.stderr)
    return 0


def build_rows(results):
    rsa_sign = get(results, CRYPTOFUN_PKG, f"BenchmarkRSASignSHA256/keyLength:{RSA_KEYLEN}")
    rsa_verify_one = get(results, CRYPTOFUN_PKG, f"BenchmarkRSAVerifySHA256/keyLength:{RSA_KEYLEN}")
    ed_sign = get(results, CRYPTOFUN_PKG, "BenchmarkEd25519phSign")
    # Note upstream has a typo: Ed2519phVerify (missing one '5').
    ed_verify_one = get(results, CRYPTOFUN_PKG, "BenchmarkEd2519phVerify")

    def agg_sign(pkg, n):
        return get(results, pkg, f"BenchmarkSign/numPrevSigs:{n}")

    def agg_verify(pkg, n):
        # numSigs is never zero in the benchmark; callers handle n=0 separately.
        return get(results, pkg, f"BenchmarkVerify/numSigs:{n}")

    rows = []
    for n in NS:
        n_for_verify = 1 if n == 0 else n  # duplicate numSigs=1 at n=0
        row = [
            n,
            rsa_sign,
            n_for_verify * rsa_verify_one,
            ed_sign,
            n_for_verify * ed_verify_one,
            agg_sign(BGLS03_PKG, n),
            agg_verify(BGLS03_PKG, n_for_verify),
            agg_sign(B03_PKG, n),
            agg_verify(B03_PKG, n_for_verify),
            agg_sign(BGOY07_PKG, n),
            agg_verify(BGOY07_PKG, n_for_verify),
        ]
        rows.append(row)
    return rows


HEADER_LINES = [
    "# Generated by extract_fig6.py from go benchmark output.",
    "# Times are in nanoseconds.",
    "#",
    "# - For sign, numSigs is the number of existing signatures on the signature",
    "#   being signed.",
    "# - For verify, numSigs is the number of signatures in the",
    "#   aggregate/multi-signature. numSigs=0 copies the numSigs=1 value so the",
    "#   plot looks nice.",
    "# - For RSA and ED25519, the sign column is the time to sign one message",
    f"#   (RSA key size: {RSA_KEYLEN}-bit); verify is single-verify * numSigs.",
    "#",
    "#           RSA                 ED25519             BGLS03                  B03                 BGOY07",
    "# numSigs   sign    verify      sign    verify      sign        verify      sign    verify      sign        verify",
]


def format_rows(rows):
    # Column widths chosen to roughly align with the sample data.
    widths = [8, 7, 11, 7, 11, 11, 11, 7, 11, 11, 11]
    out = []
    for row in rows:
        cells = [str(row[0]).ljust(widths[0])]
        # group columns after first in pairs of (sign width, verify width):
        for i, w in enumerate(widths[1:], start=1):
            cells.append(str(row[i]).rjust(w))
        # Join with 3-space gap to separate scheme groups after verify columns.
        line = cells[0] + " " + " ".join(cells[1:])
        out.append(line)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("inputs", nargs="+", help="go test -bench output files")
    ap.add_argument("-o", "--output", default="fig6.dat", help="output .dat file")
    args = ap.parse_args()

    results = parse(args.inputs)
    rows = build_rows(results)

    with open(args.output, "w") as f:
        f.write("\n".join(HEADER_LINES) + "\n")
        f.write(format_rows(rows))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
